    <ul>
        <li><strong>Trust and Transparency</strong>: We value the trust you place in us and believe in being transparent about how your data is collected, used, and protected.</li>
        <li><strong>Security Measures</strong>: Our platform employs robust security measures to prevent unauthorized access, ensuring that your personal information remains confidential.</li>
        <li><strong>Compliance with Regulations</strong>: We adhere to the guidelines and policies set forth by Google Play and other regulatory bodies, prioritizing compliance with industry standards.</li>
    </ul>

    <h2>Deleting Your Account on Houzi Real Estate App</h2>
    <p>Follow these steps to delete your account on the Houzi app:</p>
    <ol>
        <li><strong>Navigate to Your Profile</strong>: Click on the 'Profile' tab from the home screen bottom section to access your user profile settings.</li>
        <li><strong>Manage Your Profile</strong>: Within your profile tab, locate the 'Manage Profile' button. Tapping it will open the Manager Profile section.</li>
        <li><strong>Delete My Account</strong>: In the Manager Profile screen, press the red button titled 'Delete My Account' to initiate the account deletion process.</li>
    </ol>
    <p>You can at any time delete this information about you on our website and mobile app.</p>

    <h2>Delete Information via Website</h2>
    <p>Login to our website, and go to profile settings from the top right profile photo. Scroll down to the bottom, where you should see a red <strong>Delete My Account</strong> button. Press it, and all of your data will be deleted.</p>
    <p class="note">Note: Screenshots demonstrating how to access these options are available in the app and on our website.</p>

