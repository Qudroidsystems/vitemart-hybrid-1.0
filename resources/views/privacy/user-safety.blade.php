    <p>For a better experience, while using our Service, we may require you to provide us with certain personally identifiable information, including but not limited to First Name, Last Name, Email, Address, City, Country. The information that we request will be retained by us and used as described in our <a href="/api/privacy-policy">Privacy Policy</a>.</p>
